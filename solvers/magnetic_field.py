"""Magnetic field solver for solenoid coils."""

import numpy as np
from scipy.special import ellipk, ellipe
import sys
import os
sys.path.insert(0, os.path.dirname(os.path.dirname(__file__)))

from data.coils import Solenoid
from data.solutions import MagneticFieldSolution
from utils.constants import MU0


class BFieldSolver:
    """Computes B(r,z) using elliptic integrals for circular loops."""

    def __init__(self, solenoid: Solenoid):
        self.sol = solenoid

    def _turn_filament_grid(self, turn, n_div: int = 4): 
        if n_div % 2 != 0: 
            raise ValueError("n_div must be an even number.")
            
        if not hasattr(turn.cable, "stack"):
            return [(turn.r_center, turn.z_center, turn.current)]

        filaments = []
        slot_current = turn.current / turn.cable.N_slots
        filament_current = slot_current / (n_div * n_div)
        
        R_slot = turn.cable.slot_radius
        h_cell = turn.cable.stack.height / n_div
        w_cell = turn.cable.stack.width / n_div

        for idx in range(turn.cable.N_slots):
            angle = 2 * np.pi * idx / turn.cable.N_slots
            cos_a = np.cos(angle)
            sin_a = np.sin(angle)
            
            for jdx in range(n_div * n_div):
                line_rec = jdx // n_div
                column_rec = jdx % n_div
                
                # Internal grid dimensions
                x_c = w_cell/2 + column_rec * w_cell - turn.cable.stack.width/2
                y_c = h_cell/2 + line_rec * h_cell - turn.cable.stack.height/2
                
                # Here beware that grid coordinates x and y are affected to the converse local axes.
                x_local = R_slot + y_c
                y_local = x_c
    
                r_rot = x_local * cos_a - y_local * sin_a
                z_rot = x_local * sin_a + y_local * cos_a
                
                # Placement dans le référentiel global du solénoïde
                r_global = turn.r_center + r_rot
                z_global = turn.z_center + z_rot
                
                filaments.append((r_global, z_global, filament_current))
                
        return filaments

    def _turn_field(self, turn, R: np.ndarray, Z: np.ndarray, n_div: int = 4):
            """Field generated by one turn using a smeared filament model."""
            Br_tot = np.zeros_like(R, dtype=float)
            Bz_tot = np.zeros_like(R, dtype=float)
            for r_f, z_f, I_f in self._turn_filament_grid(turn, n_div=n_div):
                br, bz = self._loop_field(r_f, z_f, I_f, R, Z)
                Br_tot += br
                Bz_tot += bz
            return Br_tot, Bz_tot
    
    def compute(
            self,
            r_max: float = None,
            z_max: float = None,
            nr: int = 60,
            nz: int = 80,
            exclude_turn_singularities: bool = True,
            filament_grid_size: int = 4,
        ) -> MagneticFieldSolution:
            """Compute magnetic field solution using a distributed filament model."""
            if r_max is None:
                r_max = self.sol.r_outer * 2.0
            if z_max is None:
                z_max = self.sol.height * 0.75
    
            r_1d = np.linspace(0, r_max, nr)
            z_1d = np.linspace(-z_max, z_max, nz)
            R, Z = np.meshgrid(r_1d, z_1d, indexing='ij')
    
            Br_tot = np.zeros((nr, nz), dtype=float)
            Bz_tot = np.zeros((nr, nz), dtype=float)
    
            for lay in self.sol.layers:
                br, bz = self._turn_field(lay, R, Z, n_div=filament_grid_size)
                Br_tot += br
                Bz_tot += bz
    
            B_mag = np.sqrt(Br_tot**2 + Bz_tot**2)
    
            if exclude_turn_singularities:
                # The distributed model removes the exact filament singularity, but
                # we still filter any non-finite values for safety.
                B_mag = np.nan_to_num(B_mag, nan=0.0, posinf=np.finfo(float).max, neginf=-np.finfo(float).max)
                Br_tot = np.nan_to_num(Br_tot, nan=0.0, posinf=np.finfo(float).max, neginf=-np.finfo(float).max)
                Bz_tot = np.nan_to_num(Bz_tot, nan=0.0, posinf=np.finfo(float).max, neginf=-np.finfo(float).max)
    
            return MagneticFieldSolution(
                r=r_1d,
                z=z_1d,
                Br=Br_tot,
                Bz=Bz_tot,
                Bmag=B_mag
            )
    
    def external_field_at_point(self, r_eval: float, z_eval: float, source_layer_indices: list[int], n_div: int = 4) -> tuple[float, float]:
        """
        Compute (Br, Bz) at point (r_eval, z_eval), 
        ggenrated by layers in source_layer_indices.
        """
        Br_ext = 0.0
        Bz_ext = 0.0
        
        R_arr = np.array([[r_eval]])
        Z_arr = np.array([[z_eval]])
        
        for idx in source_layer_indices:
            lay = self.sol.layers[idx]
            br, bz = self._turn_field(lay, R_arr, Z_arr, n_div=n_div)
            Br_ext += br[0, 0]
            Bz_ext += bz[0, 0]
            
        return Br_ext, Bz_ext
    
    def _loop_field(self, a: float, z0: float, I: float,
                        R: np.ndarray, Z: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
            """Field from single loop."""
            r = np.where(R < 1e-9, 1e-9, R)
            dz = Z - z0
            Q = (a + r)**2 + dz**2
            D = (a - r)**2 + dz**2
            k2 = np.clip(4 * a * r / Q, 0, 1 - 1e-10)
            K = ellipk(k2)
            E = ellipe(k2)
            sqQ = np.sqrt(Q)
            pre = MU0 * I / (2 * np.pi)
            Bz = pre / sqQ * (K + (a**2 - r**2 - dz**2) / D * E)
            Br = pre * dz / (r * sqQ) * (-K + (a**2 + r**2 + dz**2) / D * E)
            Br = np.where(R < 1e-9, 0.0, Br)
            return Br, Bz